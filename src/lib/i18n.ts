export function useTT() {
  const idioma = useStore((s) => s.design.idioma);
  const custom = useStore((s) => s.traducoes);
  return (text: string | undefined | null) => {
    if (!text) return text ?? "";
    if (idioma === "pt") return text;
    return (
      custom?.[idioma]?.[text] ??
      builtin[idioma]?.[text] ??
      text
    );
  };
}