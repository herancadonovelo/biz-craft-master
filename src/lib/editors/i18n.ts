export const EDITOR_UI_STRINGS: string[] = ROWS.map((r) => r[0]);

function build(index: 1 | 2 | 3): Record<string, string> {
  const out: Record<string, string> = {};
  for (const row of ROWS) out[row[0]] = row[index];
  return out;
}

/** Glossário estático dos editores técnicos (excepto tricô). */
export const EDITORS_GLOSSARY: Record<EditorLang, Record<string, string>> = {
  en: build(1),
  es: build(2),
  fr: build(3),
};

/** Tradução offline de uma string dos editores (undefined se desconhecida). */
export function editorTranslate(lang: string, source: string): string | undefined {
  const dict = (EDITORS_GLOSSARY as Record<string, Record<string, string>>)[lang];
  return dict?.[source.trim()];
}
